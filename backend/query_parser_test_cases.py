"""Representative evaluation corpus for the Phase 3C-C deterministic parser.

Each case states what the parser *should* understand.  The corpus is written
from the QuerySpec contract and the ARGO data model, not by recording whatever
the parser currently returns, so that a parser regression shows up as a
failure rather than as a silent expectation change.

The cases are pure text: nothing here imports a database driver, ChromaDB,
Ollama or NetCDF.
"""

from __future__ import annotations

from dataclasses import dataclass

from query_spec import (
    Aggregation,
    DataMode,
    Intent,
    MeasurementValues,
    Parameter,
    QcScope,
    SortDirection,
    SortField,
    ValidationStatus,
)


@dataclass(frozen=True)
class ParserCase:
    """One query and the behaviour it must produce."""

    query: str
    intent: Intent
    status: ValidationStatus
    category: str

    parameters: tuple[Parameter, ...] = ()
    wmos: tuple[int, ...] = ()
    cycles: tuple[int, ...] = ()
    values: MeasurementValues | None = None
    data_mode: DataMode | None = None
    aggregations: tuple[Aggregation, ...] = ()
    qc_scope: QcScope | None = None
    qc_flags: frozenset[str] | None = None
    pressure: tuple[float, float] | None = None
    depth_present: bool | None = None
    limit: int | None = None
    sort_field: SortField | None = None
    sort_direction: SortDirection | None = None
    has_time_range: bool | None = None
    time_end: str | None = None
    has_bbox: bool | None = None
    reason_contains: str | None = None

    @property
    def label(self) -> str:
        return f"{self.category}: {self.query}"


